using System.Text.RegularExpressions;

namespace TerminalChatSystem2026
{
    class Program
    {
        static string clan = "Без клана", title = "Игрок", nick = "Player123";
        static ConsoleColor clanCol = ConsoleColor.White, titleCol = ConsoleColor.White, nickCol = ConsoleColor.White;
        static ConsoleColor msgDefaultCol = ConsoleColor.Green;

        static int messageCount = 0;
        static int commandCount = 0;
        static DateTime startTime = DateTime.Now;

        static List<Action> chatHistory = new List<Action>();

        static readonly Dictionary<string, ConsoleColor> colorMap = new Dictionary<string, ConsoleColor>(StringComparer.OrdinalIgnoreCase)
        {
            {"White", ConsoleColor.White}, {"Red", ConsoleColor.Red}, {"Green", ConsoleColor.Green},
            {"Blue", ConsoleColor.Blue}, {"Yellow", ConsoleColor.Yellow}, {"Cyan", ConsoleColor.Cyan},
            {"Magenta", ConsoleColor.Magenta}, {"Gray", ConsoleColor.Gray}, {"DarkRed", ConsoleColor.DarkRed},
            {"DarkGreen", ConsoleColor.DarkGreen}, {"DarkBlue", ConsoleColor.DarkBlue}, {"DarkCyan", ConsoleColor.DarkCyan},
            {"DarkMagenta", ConsoleColor.DarkMagenta}, {"DarkYellow", ConsoleColor.DarkYellow}, {"DarkGray", ConsoleColor.DarkGray}
        };

        static readonly string[] hints = {
            "/chat clan rename", "/chat title rename", "/chat nick rename",
            "/chat message", "/chat full reset", "/chat title reset",
            "/chat clan reset", "/chat nick reset", "/chat message reset",
            "/chat clear", "/color", "/stats", "/stop"
        };

        static void Main()
        {
            Console.OutputEncoding = System.Text.Encoding.UTF8;
            while (true)
            {
                RenderScreen();
                string input = ReadWithInlineHint("message: ");

                if (string.IsNullOrWhiteSpace(input)) continue;
                if (input.ToLower() == "/stop") break;
                if (input.ToLower() == "/chat clear") { chatHistory.Clear(); continue; }

                if (input.StartsWith("/"))
                {
                    commandCount++;
                    ExecuteCommand(input);
                }
                else
                {
                    messageCount++;
                    AddMessage(input);
                }
            }
        }

        static void RenderScreen()
        {
            Console.Clear();
            foreach (var msg in chatHistory) msg.Invoke();
            Console.WriteLine();
        }

        static string ReadWithInlineHint(string prompt)
        {
            Console.Write(prompt);
            string input = "";
            int startX = Console.CursorLeft;

            while (true)
            {
                var key = Console.ReadKey(true);
                if (key.Key == ConsoleKey.Enter) { Console.WriteLine(); return input; }
                if (key.Key == ConsoleKey.Backspace) input = input.Length > 0 ? input[..^1] : "";
                else if (!char.IsControl(key.KeyChar)) input += key.KeyChar;

                Console.SetCursorPosition(startX, Console.CursorTop);
                Console.Write(new string(' ', Console.WindowWidth - startX));
                Console.SetCursorPosition(startX, Console.CursorTop);
                Console.Write(input);

                if (input.StartsWith("/") && !string.IsNullOrEmpty(input))
                {
                    string match = hints.FirstOrDefault(h => h.StartsWith(input, StringComparison.OrdinalIgnoreCase));
                    if (match != null && match.Length > input.Length)
                    {
                        Console.ForegroundColor = ConsoleColor.DarkGray;
                        Console.Write(match[input.Length..]);
                        Console.ResetColor();
                    }
                }
                Console.SetCursorPosition(startX + input.Length, Console.CursorTop);
            }
        }

        static void AddMessage(string text)
        {
            bool isWhite = text.StartsWith("!");
            string cleanText = isWhite ? text[1..] : text;
            ConsoleColor activeColor = isWhite ? ConsoleColor.White : msgDefaultCol;

            var cC = clan; var tC = title; var nC = nick;
            var cCol = clanCol; var tCol = titleCol; var nCol = nickCol;
            var mCol = activeColor;

            chatHistory.Add(() => {
                Console.ResetColor(); Console.Write("[");
                Console.ForegroundColor = cCol; Console.Write(cC);
                Console.ResetColor(); Console.Write("] ");
                Console.ForegroundColor = tCol; Console.Write(tC);
                Console.Write(" ");
                Console.ForegroundColor = nCol; Console.Write(nC);
                Console.ResetColor(); Console.Write(" => ");
                Console.ForegroundColor = mCol; Console.WriteLine(cleanText);
                Console.ResetColor();
            });
        }

        static void ExecuteCommand(string cmd)
        {
            string[] args = cmd.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            if (args.Length == 0) return;

            string baseCmd = args[0].ToLower();

            if (baseCmd == "/stats")
            {
                TimeSpan sessionTime = DateTime.Now - startTime;
                Console.WriteLine("\n=== ВАША СТАТИСТИКА ===");
                Console.WriteLine($"Отправлено сообщений: {messageCount}");
                Console.WriteLine($"Выполнено команд: {commandCount}");
                Console.WriteLine($"Время в консоли: {sessionTime.Hours}ч {sessionTime.Minutes}м {sessionTime.Seconds}с");
                Console.WriteLine("=======================");
                Console.WriteLine("Нажмите любую клавишу..."); Console.ReadKey();
                return;
            }

            if (baseCmd == "/color")
            {
                Console.WriteLine("\n--- Список доступных цветов ---");
                foreach (var kvp in colorMap)
                    Console.WriteLine($"{kvp.Key} - {Translate(kvp.Key)}");
                Console.WriteLine("Нажмите любую клавишу..."); Console.ReadKey();
                return;
            }

            if (args.Length >= 3 && baseCmd == "/chat")
            {
                string target = args[1].ToLower();
                string action = args[2].ToLower();

                if (action == "reset")
                {
                    if (target is "full" or "clan") { clan = "Без клана"; clanCol = ConsoleColor.White; }
                    if (target is "full" or "title") { title = "Игрок"; titleCol = ConsoleColor.White; }
                    if (target is "full" or "nick") { nick = "Player123"; nickCol = ConsoleColor.White; }
                    if (target is "full" or "message") { msgDefaultCol = ConsoleColor.Green; }
                }
                else if (action == "rename" && args.Length >= 5)
                {
                    if (colorMap.TryGetValue(args[4], out ConsoleColor newCol))
                    {
                        if (target == "clan") { clan = args[3]; clanCol = newCol; }
                        if (target == "title") { title = args[3]; titleCol = newCol; }
                        if (target == "nick" && Regex.IsMatch(args[3], @"^[a-zA-Z0-9\W]{3,16}$"))
                        { nick = args[3]; nickCol = newCol; }
                    }
                }
                else if (target == "message" && colorMap.TryGetValue(args[2], out ConsoleColor mCol))
                {
                    msgDefaultCol = mCol;
                }
            }
        }

        static string Translate(string color) => color.ToLower() switch
        {
            "white" => "Белый",
            "red" => "Красный",
            "green" => "Зеленый",
            "blue" => "Синий",
            "yellow" => "Желтый",
            "cyan" => "Голубой",
            "magenta" => "Пурпурный",
            "gray" => "Серый",
            "darkred" => "Темно-красный",
            "darkgreen" => "Темно-зеленый",
            "darkblue" => "Темно-синий",
            "darkcyan" => "Темно-голубой",
            "darkmagenta" => "Темно-пурпурный",
            "darkyellow" => "Темно-желтый",
            "darkgray" => "Темно-серый",
            _ => color
        };
    }
